def build_database():
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.executescript("""
    PRAGMA foreign_keys = ON;

    CREATE TABLE exam_rounds (
        round_id INTEGER PRIMARY KEY,
        round_title TEXT NOT NULL,
        exam_year INTEGER NOT NULL,
        exam_date TEXT NOT NULL,
        agency TEXT NOT NULL,
        key_trend TEXT NOT NULL
    );

    CREATE TABLE categories_domain (
        domain_id INTEGER PRIMARY KEY,
        domain_code TEXT NOT NULL UNIQUE,
        domain_name TEXT NOT NULL,
        description TEXT NOT NULL
    );

    CREATE TABLE categories_qtype (
        qtype_id INTEGER PRIMARY KEY,
        qtype_code TEXT NOT NULL UNIQUE,
        qtype_name TEXT NOT NULL,
        default_score INTEGER NOT NULL,
        description TEXT NOT NULL
    );

    CREATE TABLE questions (
        question_id INTEGER PRIMARY KEY AUTOINCREMENT,
        round_id INTEGER NOT NULL,
        question_no INTEGER NOT NULL,
        domain_id INTEGER NOT NULL,
        qtype_id INTEGER NOT NULL,
        subtopic TEXT NOT NULL,
        title TEXT NOT NULL,
        question_text TEXT NOT NULL,
        code_or_log TEXT DEFAULT '',
        choices_json TEXT NOT NULL,
        correct_choice INTEGER,
        answer_text TEXT NOT NULL,
        core_keywords TEXT NOT NULL,
        explanation TEXT NOT NULL,
        source TEXT NOT NULL,
        FOREIGN KEY (round_id) REFERENCES exam_rounds(round_id),
        FOREIGN KEY (domain_id) REFERENCES categories_domain(domain_id),
        FOREIGN KEY (qtype_id) REFERENCES categories_qtype(qtype_id),
        UNIQUE(round_id, question_no)
    );

    CREATE TABLE domain_analytics (
        domain_id INTEGER PRIMARY KEY,
        domain_name TEXT NOT NULL,
        total_questions INTEGER NOT NULL,
        share_pct REAL NOT NULL,
        mcq_count INTEGER NOT NULL,
        short_count INTEGER NOT NULL,
        round_appearances INTEGER NOT NULL,
        primary_qtype TEXT NOT NULL,
        FOREIGN KEY (domain_id) REFERENCES categories_domain(domain_id)
    );

    CREATE VIEW v_questions_full AS
    SELECT
        q.question_id,
        q.round_id,
        r.round_title,
        r.exam_year,
        r.agency,
        q.question_no,
        q.domain_id,
        d.domain_name,
        q.qtype_id,
        t.qtype_name,
        t.default_score,
        q.subtopic,
        q.title,
        q.question_text,
        q.code_or_log,
        q.choices_json,
        q.correct_choice,
        q.answer_text,
        q.core_keywords,
        q.explanation,
        q.source
    FROM questions q
    JOIN exam_rounds r ON q.round_id = r.round_id
    JOIN categories_domain d ON q.domain_id = d.domain_id
    JOIN categories_qtype t ON q.qtype_id = t.qtype_id;
    """)

    cur.executemany("INSERT INTO exam_rounds VALUES (?, ?, ?, ?, ?, ?)", EXAM_ROUNDS)
    cur.executemany("INSERT INTO categories_domain VALUES (?, ?, ?, ?)", CATEGORIES_DOMAIN)
    cur.executemany("INSERT INTO categories_qtype VALUES (?, ?, ?, ?, ?)", CATEGORIES_QTYPE)

    q_rows = []
    for item in RAW_QUESTIONS:
        (round_id, q_no, domain_id, qtype_id, subtopic, title, question_text,
         code_or_log, choices, correct_choice, answer_text, core_keywords, explanation, source) = item

        # Strict validation during build
        assert title.strip(), f"Empty title at round={round_id}, no={q_no}"
        assert question_text.strip(), f"Empty question_text at round={round_id}, no={q_no}"
        assert answer_text.strip(), f"Empty answer_text at round={round_id}, no={q_no}"
        assert explanation.strip(), f"Empty explanation at round={round_id}, no={q_no}"
        assert source.strip(), f"Empty source at round={round_id}, no={q_no}"
        if qtype_id == 1:
            assert len(choices) == 4 and all(c.strip() for c in choices), f"Invalid MCQ choices at {round_id}-{q_no}"
            assert correct_choice in (1, 2, 3, 4), f"Invalid correct_choice at {round_id}-{q_no}"
        else:
            assert choices == [] and correct_choice is None, f"Invalid SHORT format at {round_id}-{q_no}"

        q_rows.append((
            round_id, q_no, domain_id, qtype_id, subtopic, title, question_text,
            code_or_log, json.dumps(choices, ensure_ascii=False), correct_choice,
            answer_text, core_keywords, explanation, source
        ))

    cur.executemany("""
        INSERT INTO questions (
            round_id, question_no, domain_id, qtype_id, subtopic, title,
            question_text, code_or_log, choices_json, correct_choice,
            answer_text, core_keywords, explanation, source
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, q_rows)

    total_q = len(RAW_QUESTIONS)
    qtype_name_map = {t[0]: t[2] for t in CATEGORIES_QTYPE}
    analytics_rows = []
    for dom_id, dom_code, dom_name, _ in CATEGORIES_DOMAIN:
        dom_qs = [q for q in RAW_QUESTIONS if q[2] == dom_id]
        cnt = len(dom_qs)
        share = round((cnt / total_q) * 100, 1) if total_q else 0.0
        mcq_c = sum(1 for q in dom_qs if q[3] == 1)
        short_c = sum(1 for q in dom_qs if q[3] == 2)
        round_app = len(set(q[0] for q in dom_qs))
        qtype_counter = Counter(q[3] for q in dom_qs)
        primary_qt = qtype_name_map[qtype_counter.most_common(1)[0][0]] if qtype_counter else '-'
        analytics_rows.append((
            dom_id, dom_name, cnt, share, mcq_c, short_c, round_app, primary_qt
        ))

    cur.executemany("INSERT INTO domain_analytics VALUES (?, ?, ?, ?, ?, ?, ?, ?)", analytics_rows)
    conn.commit()

    # SQL 덤프 저장
    with open(SQL_DUMP_PATH, 'w', encoding='utf-8') as f:
        for line in conn.iterdump():
            f.write(f"{line}\n")

